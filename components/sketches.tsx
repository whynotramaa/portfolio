export function Ink({ d, id, boil = false, className = "sketch" }: { d: Drawing; id: string; boil?: boolean; className?: string }) {
  return (
    <svg className={className} viewBox={d.view ?? "0 0 400 280"} aria-hidden="true">
      <defs>
        <filter id={id}>
          <feTurbulence type="fractalNoise" baseFrequency="0.03" numOctaves={2} seed={id.length}>
            {boil && <animate attributeName="seed" values="1;4;7;10" dur="0.6s" calcMode="discrete" repeatCount="indefinite" />}
          </feTurbulence>
          <feDisplacementMap in="SourceGraphic" scale={3.4} />
        </filter>
      </defs>
      <path className="sk-blob" d={d.blob} />
      <g filter={`url(#${id})`}>
        {d.paper?.map((p, k) => <path key={`p${k}`} className="sk-paper" d={p} />)}
        {d.accent?.map((p, k) => <path key={`a${k}`} className="sk-accent" d={p} />)}
        {d.ink.map((p, k) => (
          <path key={`i${k}`} className="sk-ink" d={p} pathLength={1} style={{ "--k": k } as CSSProperties} />
        ))}
        {d.labels?.map((l) => (
          <text
            key={l.t}
            className={`sk-label sk-${l.font ?? "hand"}`}
            x={l.x}
            y={l.y}
            fontSize={l.s}
            textAnchor={l.start ? "start" : "middle"}
            transform={l.r ? `rotate(${l.r} ${l.x} ${l.y})` : undefined}
          >
            {l.t}
          </text>
        ))}
      </g>
    </svg>
  );
}

export function Sketch({ index, boil }: { index: number; boil: boolean }) {
  return <Ink d={drawings[index % drawings.length]} id={`sk-wobble-${index}`} boil={boil} />;
}
